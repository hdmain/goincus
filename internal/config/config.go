package config

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"

	"gopkg.in/yaml.v3"

	"github.com/hdmain/goincus/internal/secrets"
)

// Config holds all runtime settings for the goincus service.
type Config struct {
	Server   ServerConfig   `yaml:"server"`
	Auth     AuthConfig     `yaml:"auth"`
	Database DatabaseConfig `yaml:"database"`
	Redis    RedisConfig    `yaml:"redis"`
	Incus    IncusConfig    `yaml:"incus"`
	Ports    PortsConfig    `yaml:"ports"`
	Defaults DefaultsConfig `yaml:"defaults"`
}

type ServerConfig struct {
	Host         string   `yaml:"host"`
	Port         int      `yaml:"port"`
	ReadTimeout  Duration `yaml:"read_timeout"`
	WriteTimeout Duration `yaml:"write_timeout"`
	IdleTimeout  Duration `yaml:"idle_timeout"`
}

type AuthConfig struct {
	// APIKeys are accepted via Authorization: Bearer <key> or X-API-Key.
	APIKeys []string `yaml:"api_keys"`
}

type DatabaseConfig struct {
	Host     string `yaml:"host"`
	Port     int    `yaml:"port"`
	User     string `yaml:"user"`
	Password string `yaml:"password"`
	Name     string `yaml:"name"`
	SSLMode  string `yaml:"sslmode"`
	MaxConns int32  `yaml:"max_conns"`
	MinConns int32  `yaml:"min_conns"`
}

type RedisConfig struct {
	Host      string `yaml:"host"`
	Port      int    `yaml:"port"`
	Password  string `yaml:"password"`
	DB        int    `yaml:"db"`
	KeyPrefix string `yaml:"key_prefix"`
}

type IncusConfig struct {
	SocketPath    string   `yaml:"socket_path"`
	Project       string   `yaml:"project"`
	StoragePool   string   `yaml:"storage_pool"`
	Network       string   `yaml:"network"`
	ImageServer   string   `yaml:"image_server"`
	ImageProtocol string   `yaml:"image_protocol"`
	DefaultImage  string   `yaml:"default_image"`
	Profiles      []string `yaml:"profiles"`
}

type PortsConfig struct {
	HostRangeStart       int   `yaml:"host_range_start"`
	HostRangeEnd         int   `yaml:"host_range_end"`
	DefaultInternalPorts []int `yaml:"default_internal_ports"`
}

type DefaultsConfig struct {
	CPUCores  int `yaml:"cpu_cores"`
	MemoryMB  int `yaml:"memory_mb"`
	StorageGB int `yaml:"storage_gb"`
	Processes int `yaml:"processes"`
}

// Addr returns the HTTP listen address.
func (s ServerConfig) Addr() string {
	return fmt.Sprintf("%s:%d", s.Host, s.Port)
}

// DSN returns a PostgreSQL connection string.
func (d DatabaseConfig) DSN() string {
	return fmt.Sprintf(
		"host=%s port=%d user=%s password=%s dbname=%s sslmode=%s",
		d.Host, d.Port, d.User, d.Password, d.Name, d.SSLMode,
	)
}

// Addr returns host:port for Redis.
func (r RedisConfig) Addr() string {
	return fmt.Sprintf("%s:%d", r.Host, r.Port)
}

// Load reads configuration from a YAML file.
func Load(path string) (*Config, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read config: %w", err)
	}

	cfg := Default()
	if err := yaml.Unmarshal(data, cfg); err != nil {
		return nil, fmt.Errorf("parse config: %w", err)
	}

	if err := cfg.Validate(); err != nil {
		return nil, err
	}
	return cfg, nil
}

// Save writes the config as YAML with restrictive permissions.
func Save(path string, cfg *Config) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("mkdir config dir: %w", err)
	}
	data, err := yaml.Marshal(cfg)
	if err != nil {
		return fmt.Errorf("marshal config: %w", err)
	}
	header := []byte("# Generated by goincus init — keep this file private.\n")
	if err := os.WriteFile(path, append(header, data...), 0o600); err != nil {
		return fmt.Errorf("write config: %w", err)
	}
	return nil
}

