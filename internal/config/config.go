// GenerateInitialized builds a default config with fresh passwords and API keys.
func GenerateInitialized() (*Config, error) {
	cfg := Default()

	dbPass, err := secrets.RandomPassword(24)
	if err != nil {
		return nil, err
	}
	redisPass, err := secrets.RandomPassword(24)
	if err != nil {
		return nil, err
	}
	apiKey, err := secrets.RandomAPIKey()
	if err != nil {
		return nil, err
	}
	adminKey, err := secrets.RandomAPIKey()
	if err != nil {
		return nil, err
	}

	cfg.Database.Password = dbPass
	cfg.Redis.Password = redisPass
	cfg.Auth.APIKeys = []string{apiKey, adminKey}
	return cfg, nil
}

// Validate checks required fields and port ranges.
func (c *Config) Validate() error {
	if c.Server.Port <= 0 || c.Server.Port > 65535 {
		return fmt.Errorf("invalid server port: %d", c.Server.Port)
	}
	if c.Database.Host == "" || c.Database.Port <= 0 {
		return fmt.Errorf("database host/port required")
	}
	if c.Redis.Host == "" || c.Redis.Port <= 0 {
		return fmt.Errorf("redis host/port required")
	}
	if c.Ports.HostRangeStart >= c.Ports.HostRangeEnd {
		return fmt.Errorf("invalid host port range: %d-%d", c.Ports.HostRangeStart, c.Ports.HostRangeEnd)
	}
	if c.Defaults.CPUCores < 1 {
		return fmt.Errorf("defaults.cpu_cores must be >= 1")
	}
	if c.Defaults.MemoryMB < 64 {
		return fmt.Errorf("defaults.memory_mb must be >= 64")
	}
	if c.Defaults.StorageGB < 1 {
		return fmt.Errorf("defaults.storage_gb must be >= 1")
	}
	if len(c.Auth.APIKeys) == 0 {
		return fmt.Errorf("auth.api_keys must contain at least one key (run: goincus init)")
	}
	for _, key := range c.Auth.APIKeys {
		if strings.Contains(key, "REPLACE_WITH") {
			return fmt.Errorf("%s looks like a package template — run: sudo goincus init (do not overwrite an existing working config unless secrets were lost)", setupHintPath())
		}
	}
	if strings.Contains(c.Database.Password, "REPLACE_WITH") || strings.Contains(c.Redis.Password, "REPLACE_WITH") {
		return fmt.Errorf("%s has template passwords — apt upgrade used to overwrite this file; restore a backup or run: sudo goincus init --force", setupHintPath())
	}
	return nil
}

func setupHintPath() string {
	return "/etc/goincus/config.yaml"
}

// ValidAPIKey reports whether key is configured.
func (c *Config) ValidAPIKey(key string) bool {
	if key == "" {
		return false
	}
	for _, k := range c.Auth.APIKeys {
		if k != "" && k == key {
			return true
		}
	}
	return false
}
